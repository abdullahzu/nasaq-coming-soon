let language = "ar";

function resolve(object, path) {
  return path.split(".").reduce((value, key) => value?.[key], object);
}

function setLanguage(nextLanguage) {
  language = nextLanguage;
  const selected = copy[language];
  const isArabic = language === "ar";

  document.documentElement.lang = language;
  document.documentElement.dir = isArabic ? "rtl" : "ltr";
  document.querySelector("#site-shell").dir = isArabic ? "rtl" : "ltr";
  document.title = selected.meta.title;
  document.querySelector('meta[name="description"]').content = selected.meta.description;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = resolve(selected, element.dataset.i18n);
    if (typeof value === "string") element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = resolve(selected, element.dataset.i18nPlaceholder);
    if (typeof value === "string") element.placeholder = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = resolve(selected, element.dataset.i18nAlt);
    if (typeof value === "string") element.alt = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = resolve(selected, element.dataset.i18nAria);
    if (typeof value === "string") element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-option]").forEach((option) => {
    option.textContent = selected.options[option.dataset.option];
  });
  document.querySelectorAll("[data-service-secondary]").forEach((element) => {
    element.textContent = resolve(selected, `services.${element.dataset.serviceSecondary}.secondary`);
    element.dir = isArabic ? "ltr" : "rtl";
  });
  document.querySelectorAll("[data-direction-arrow]").forEach((element) => { element.textContent = isArabic ? "↖" : "↗"; });

  const switcher = document.querySelector("#language-switch");
  switcher.textContent = selected.switchText;
  switcher.setAttribute("aria-label", selected.switchLabel);
  document.querySelector("#project-form-status").textContent = "";
}

document.querySelector("#language-switch").addEventListener("click", () => setLanguage(language === "ar" ? "en" : "ar"));

document.querySelector("#project-form").addEventListener("submit", async (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const submit = form.querySelector('button[type="submit"]');
  const status = document.querySelector("#project-form-status");
  const selected = copy[language];

  if (!form.reportValidity()) return;
  submit.disabled = true;
  status.dataset.state = "sending";
  status.textContent = selected.contact.sending;

  const fields = new FormData(form);
  const payload = Object.fromEntries(fields.entries());
  payload.language = language;

  try {
    const response = await fetch("/api/contact", {
      method: "POST",
      headers: { "Content-Type": "application/json", "Accept": "application/json" },
      body: JSON.stringify(payload),
    });
    if (!response.ok) throw new Error("Contact request failed");
    status.dataset.state = "success";
    status.textContent = selected.contact.success;
    form.reset();
  } catch {
    status.dataset.state = "error";
    status.textContent = selected.contact.error;
  } finally {
    submit.disabled = false;
  }
});

