import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
const catalogue = JSON.parse(await readFile('content/catalogue.json', 'utf8'));
const pages = ['', 'about', 'approach', 'services', 'engagements', 'concepts', 'deliverables', 'contact', 'privacy', ...catalogue.services.map(x=>'services/'+x.slug), ...catalogue.concepts.map(x=>'concepts/'+x.slug)];
assert.equal(pages.length, 30);
for (const lang of ['ar','en']) for (const page of pages) await access(`app/${lang}/${page ? page+'/' : ''}page.tsx`);
for (const file of ['public/images/pages/home-concepts-simple-v2-1536.webp', 'public/images/pages/home-concepts-simple-v2-768.webp', 'public/nasaq-full-counter-hero-v2.webp', 'public/nasaq-villa-service-trolley-layout.webp', 'worker/index.ts', 'package-lock.json']) await access(file);
const config = JSON.parse(await readFile('wrangler.jsonc','utf8'));
assert.equal(config.name,'nasaq-coming-soon');
assert.equal(config.assets.run_worker_first,true);
assert.equal(config.send_email[0].destination_address,'growth@nasaqfb.com');
console.log('Source checks passed: 60 pages, current imagery, Worker configuration and fixed email recipient.');
